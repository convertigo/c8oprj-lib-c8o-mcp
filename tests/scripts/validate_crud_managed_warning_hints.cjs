const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

// The warning on a direct edit of a kit-managed object listed the kit's ui hints, to send agents back to the kit (usage
// tests 30/10). The kit is retired from what agents see (13/11): the warning says so and sends to ngx-page-create, never
// to a kit option.

const src = fs.readFileSync(path.join(__dirname, '..', '..', 'js', 'crud_ui_refresh.js'), 'utf8');

test('the managed edit warning says the kit is retired and names ngx-page-create, never a kit option', () => {
  const context = { C8O: { util: {} }, include() {}, JSON };
  vm.createContext(context);
  vm.runInContext(src, context);
  const hints = context.C8O.crudUiRefresh.kitHintText();
  assert.match(hints, /^upsert-ngx-crud-kit is retired: change this object here, or delete its page and create it again with ngx-page-create\./);
  for (const old of ['listFields', 'listFilters', 'auth option', 'language option', 'stage final', 'Prefer `upsert-ngx-crud-kit`']) {
    assert.ok(!hints.includes(old), old);
  }
  const start = src.indexOf('function managedCrudMutationWarning');
  const body = src.slice(start, src.indexOf('\n  }\n', start));
  assert.match(body, /was generated by upsert-ngx-crud-kit\. " \+ KIT_HINTS;/);
});
