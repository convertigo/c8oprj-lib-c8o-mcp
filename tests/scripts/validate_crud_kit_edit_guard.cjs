const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

// Agents changed CRUD kit pages by hand, the warning coming after the write: every mistral-large-4 S3 replay built status
// and search filters into a kit-managed list panel that the next kit run overwrites, while ui.listFilters does it (usage
// tests 30/10). tree-get and crud-status now say a kit object is one before any edit, and tree-apply refuses a first
// write there with the kit option; the same call with override: true goes through with the warning. The backend crud_*
// sequences keep an app's own steps before their call: they are not refused.

const root = path.resolve(__dirname, '../..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');

function refresh() {
  const ctx = { C8O: { util: {} }, include() {}, JSON };
  vm.createContext(ctx);
  vm.runInContext(read('js/crud_ui_refresh.js'), ctx);
  return ctx.C8O.crudUiRefresh;
}

const trimmed = v => String(v == null ? '' : v).trim();
const bean = (className, name, comment, parent) => ({
  getClass: () => ({ getName: () => 'com.twinsoft.convertigo.beans.' + className }),
  getName: () => name, getComment: () => comment || '', getParent: () => parent || null,
  getFullQName: () => 'App.' + name, getQName: () => 'App.' + name
});

test('a kit page and what it holds are refused with the kit option; override goes through with the warning', () => {
  const R = refresh();
  const panel = bean('ngx.components.UISharedRegularComponent', 'InterventionsListPanel', 'Managed by upsert-ngx-crud-kit: list panel.');
  const filter = bean('ngx.components.UIDynamicElement', 'Filters', '', panel);
  const refusal = R.managedCrudRefusal({ trimmed }, filter);
  assert.match(refusal, /^`App\.InterventionsListPanel` is generated by upsert-ngx-crud-kit: its next run overwrites a direct edit\./);
  assert.match(refusal, /listFilters \(status select and text search above the list\)/);
  assert.match(refusal, /To change it by hand anyway, send the same call again with override: true\.$/);
  assert.match(R.managedCrudMutationWarning({ trimmed }, filter), /^Direct edits on CRUD-kit-managed UI object `App\.InterventionsListPanel`/);
  assert.equal(R.managedCrudUiInfo({ trimmed }, filter).qname, 'App.InterventionsListPanel');
});

test('an object the kit does not manage, and a backend crud_ sequence, are neither refused nor warned', () => {
  const R = refresh();
  const page = bean('ngx.components.PageComponent', 'Reports', 'A page of the app.');
  const text = bean('ngx.components.UIText', 'Title', '', page);
  assert.equal(R.managedCrudRefusal({ trimmed }, text), '');
  assert.equal(R.managedCrudMutationWarning({ trimmed }, text), '');
  const sequence = bean('sequences.GenericSequence', 'crud_delete_client', 'CRUD delete of a client.');
  const check = bean('steps.IfStep', 'RequireRole', '', sequence);
  assert.equal(R.managedCrudRefusal({ trimmed }, check), '', 'an app check in a backend sequence stays possible');
  assert.equal(R.managedCrudMutationWarning({ trimmed }, check), '');
});

test('tree-apply refuses unless override, internal callers only warn, and the answers name the kit', () => {
  const batch = read('js/databaseobject_batch.js');
  assert.match(batch, /if \(ctx && ctx\.managedGuard === "refuse" && typeof C8O\.crudUiRefresh\.managedCrudRefusal === "function"\) \{[\s\S]*?throw makeOpError\("managed_by_crud_kit", refusal, "validate", "", safeQName\(dbo\)\);/);
  assert.match(batch, /managedGuard: asTrimmed\(params\.managedGuard\) === "refuse" \? "refuse" : "warn",/);
  const apply = read('js/tools_databaseobject_tree_apply.js');
  assert.match(apply, /var overrideInput = \(typeof override !== "undefined"\) \? asBoolean\(override, false\) === true : false;/);
  assert.match(apply, /managedGuard: overrideInput \? "warn" : "refuse"/);
  assert.match(read('_c8oProject/sequences/tools_databaseobject_tree_apply.yaml'), /↓override \[variables\.RequestableVariable-\d+\]: \n  comment: Set true to change an object generated by upsert-ngx-crud-kit by hand\./);
  const schema = read('js/schema_overrides.js');
  assert.match(schema, /override: \{\n\s*type: "boolean",\n\s*default: false,/);
  assert.match(schema, /managedBy: \{ type: "string"/);
  assert.match(read('_c8oProject/sequences/tools_databaseobject_tree_get.yaml'), /↓IfManagedBy \[steps\.IfStep-\d+\]: \n    comment: Say when the target is generated by the CRUD kit\.\n    condition: notEmpty\(treeManagedBy\)/);
  assert.match(read('js/tools_databaseobject_tree_get.js'), /treeManagedBy = "upsert-ngx-crud-kit";/);
  assert.match(read('js/crud_proof.js'), /status\.ui\.managedBy = "upsert-ngx-crud-kit";\n\s*status\.ui\.kitHints = /);
});
