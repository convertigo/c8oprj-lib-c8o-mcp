const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

// upsert-crud on the database of an app in use (usage tests 29/10). Adding a field to an entity regenerated SQL that
// reads the new column while CREATE TABLE IF NOT EXISTS left the table as it was: every list failed with "object not
// found: BASE.PRIORITY" until the agent wrote ALTER TABLE itself. And every upsert-crud ran init_schema, whose seed
// deletes every row of the tables: the user's data was replaced by the demo rows. A bare DECIMAL lost the cents.

const root = path.resolve(__dirname, '../..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');

function backend() {
  const context = { C8O: {} };
  vm.createContext(context);
  vm.runInContext(read('js/crud_proof.js'), context);
  vm.runInContext(read('js/crud_backend.js'), context);
  return context.C8O.crudBackend;
}

const ctx = {
  ensureArray: v => (Array.isArray(v) ? v : v == null ? [] : [v]),
  trimmed: v => String(v == null ? '' : v).trim(),
  normalizedIdentifier: v => String(v || '').replace(/[^A-Za-z0-9_]/g, '_').toLowerCase(),
  pluralize: v => v,
  clone: v => JSON.parse(JSON.stringify(v)),
};

const DRIVERS = {
  hsqldb: { id: 'hsqldb', booleanType: 'BOOLEAN', textType: 'LONGVARCHAR', identityColumn: 'INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY' },
  sqlserver: { id: 'sqlserver', booleanType: 'BIT', textType: 'VARCHAR(MAX)', identityColumn: 'INT IDENTITY(1,1) PRIMARY KEY' },
  oracle: { id: 'oracle', booleanType: 'NUMBER(1)', textType: 'CLOB', identityColumn: 'NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' },
};

function field(column, type, extra) {
  return Object.assign({ name: column, column, type, primary: false, required: false, unique: false, defaultValue: null, references: null }, extra);
}

function spec(driver, extraFields, seed) {
  return {
    database: { driver: DRIVERS[driver || 'hsqldb'] },
    seed: seed || { enabled: true },
    entities: [{
      name: 'interventions',
      fields: [field('id', 'INT', { primary: true, required: true, unique: true }), field('titre', 'VARCHAR(255)', { required: true }),
        field('montant', 'DECIMAL')].concat(extraFields || []),
    }],
  };
}

// The columns and row count an inspection of the Atelier database gives (JDBC metadata, HSQLDB).
const ATELIER = {
  reachable: true,
  tables: { interventions: { name: 'INTERVENTIONS', rows: 5, columns: {
    id: { type: 'INTEGER(32,0)', digits: 0 }, titre: { type: 'VARCHAR(255)', digits: null }, montant: { type: 'DECIMAL(128,0)', digits: 0 } } } },
};

test('a bare DECIMAL keeps its cents, and a field default is written in the column', () => {
  const B = backend();
  assert.equal(B.mapSqlType(ctx, field('montant', 'decimal'), DRIVERS.hsqldb), 'DECIMAL(12,2)');
  assert.equal(B.mapSqlType(ctx, field('montant', 'DECIMAL(10,3)'), DRIVERS.hsqldb), 'DECIMAL(10,3)');
  assert.equal(B.mapSqlType(ctx, field('montant', 'decimal'), DRIVERS.oracle), 'NUMBER(12,2)');
  assert.equal(B.renderColumnDefinition(ctx, field('priorite', 'VARCHAR(10)', { required: true, defaultValue: "l'normale" }), DRIVERS.hsqldb),
    "priorite VARCHAR(10) DEFAULT 'l''normale' NOT NULL");
  assert.equal(B.renderColumnDefinition(ctx, field('actif', 'BOOLEAN', { defaultValue: true }), DRIVERS.sqlserver), 'actif BIT DEFAULT 1');
});

test('tables with rows are kept: no reseed, a new field is added as a column filled with its default', () => {
  const B = backend();
  const plan = B.planExistingDatabase(ctx, spec('hsqldb', [field('priorite', 'VARCHAR(10)', { required: true, defaultValue: 'normale' })]), ATELIER);
  assert.equal(plan.keep, true);
  assert.deepEqual(JSON.parse(JSON.stringify(plan.alters)), [{ table: 'interventions', column: 'priorite',
    sql: "ALTER TABLE interventions ADD COLUMN priorite VARCHAR(10) DEFAULT 'normale' NOT NULL" }]);
  assert.match(plan.notes.join('\n'), /interventions\.montant keeps 0 decimals in the database \(DECIMAL\(128,0\)\) and the spec says DECIMAL\(12,2\).*ALTER TABLE interventions ALTER COLUMN montant SET DATA TYPE DECIMAL\(12,2\)/);
});

test('a required field without a default comes nullable on a table with rows, and says so', () => {
  const B = backend();
  const plan = B.planExistingDatabase(ctx, spec('hsqldb', [field('priorite', 'VARCHAR(10)', { required: true })]), ATELIER);
  assert.equal(plan.alters[0].sql, 'ALTER TABLE interventions ADD COLUMN priorite VARCHAR(10)');
  assert.match(plan.notes.join('\n'), /interventions\.priorite is required but has no default: it was added nullable and the 5 existing rows hold NULL/);
  const sqlserver = B.planExistingDatabase(ctx, spec('sqlserver', [field('priorite', 'VARCHAR(10)', { defaultValue: 'normale' })]), ATELIER);
  assert.equal(sqlserver.alters[0].sql, "ALTER TABLE interventions ADD priorite VARCHAR(10) DEFAULT 'normale'");
  const oracle = B.planExistingDatabase(ctx, spec('oracle', [field('priorite', 'VARCHAR2(10)', { defaultValue: 'normale' })]), ATELIER);
  assert.equal(oracle.alters[0].sql, "ALTER TABLE interventions ADD (priorite VARCHAR2(10) DEFAULT 'normale')");
});

test('a fresh or empty database, an unreachable one, or seed.reset keeps the demo seed', () => {
  const B = backend();
  assert.equal(B.planExistingDatabase(ctx, spec(), { reachable: false, tables: {} }).keep, false);
  assert.equal(B.planExistingDatabase(ctx, spec(), { reachable: true, tables: {} }).keep, false);
  const empty = JSON.parse(JSON.stringify(ATELIER));
  empty.tables.interventions.rows = 0;
  assert.equal(B.planExistingDatabase(ctx, spec(), empty).keep, false);
  assert.equal(B.planExistingDatabase(ctx, spec('hsqldb', [], { enabled: true, reset: true }), ATELIER).keep, false);
  // Without a seed, init_schema creates the tables only: what upsert-crud stores once the rows are kept.
  const ddl = B.buildInitSql(ctx, spec('hsqldb', [], { enabled: false }));
  assert.doesNotMatch(ddl, /DELETE FROM|INSERT INTO/);
});

test('upsert-crud reads the database before init_schema, adds the columns after it, and skips the final reset', () => {
  const source = read('js/crud_backend.js');
  const plan = source.indexOf('var existingDatabase = C8O.crudBackend.planExistingDatabase(');
  const init = source.indexOf('C8O.crudBackend.ensureSqlTransaction(ctx, connector, "init_schema"');
  const alters = source.indexOf('C8O.crudBackend.applyAlters)(ctx, connector, existingDatabase.alters)');
  const learn = source.indexOf('var entityLearn = learnEntitySchemas(');
  assert.ok(plan > 0 && plan < init, 'the plan is made before init_schema is generated');
  assert.ok(alters > init && alters < learn, 'the columns are added before the schemas are learned');
  assert.match(source, /if \(existingDatabase\.keep\) \{\n\s*\/\/[^\n]*\n\s*spec\.seed\.enabled = false;/);
  assert.match(source, /if \(spec\.entities\.length && !existingDatabase\.keep\) \{\n\s*ctx\.requestablePayload\([^\n]*init_schema/);
});
