    def _judge_error(self, label, a, provided=None, seconds=0.0):
        if a.looks_html():
            self.r.add("errors", label, "FAIL", f"HTML answer (HTTP {a.status}, {a.content_type}): {a.body[:120]!r}")
            return
        if a.envelope is None:
            self.r.add("errors", label, "FAIL", f"not JSON (HTTP {a.status}): {a.body[:160]!r}")
            return
        inner = a.data if isinstance(a.data, dict) else {}
        msg = _message(a)
        slow = f" ({seconds:.0f} s to answer)" if seconds > 15 else ""
        if seconds > 60:
            self.r.add("errors", label, "FAIL", f"{seconds:.0f} s before the error: {msg[:140]}",
                       fix="check that the project exists before waiting for anything")
            return
        if provided and inner.get("project") and inner.get("project") != provided:
            self.r.add("errors", label, "FAIL", f"asked for project {provided}, acted on {inner.get('project')}: {a.text[:160]}")
            return
        if not a.is_error:
            nested = inner.get("result") if isinstance(inner.get("result"), dict) else inner
            status = str(nested.get("status") or "")
            if nested.get("error") or status in ("error", "failed", "missing", "not_found", "partial") or nested.get("ok") is False \
                    or nested.get("errors"):
                if not _readable(msg):
                    cause = _script_cause(nested)
                    self.r.add("errors", label, "WARN" if cause else "FAIL",
                               f"isError false, generic message {msg[:60]!r}" + (f"; the cause is only in details: {cause[:100]!r}" if cause else ""))
                else:
                    self.r.add("errors", label, "WARN" if slow else "PASS", f"isError false, status {status or 'error'}: {msg[:120]}{slow}")
            else:
                self.r.add("errors", label, "WARN", f"accepted without error: {a.text[:160] or json.dumps(a.structured)[:160]}")
            return
        if not _readable(msg):
            self.r.add("errors", label, "FAIL", f"message not readable: {msg[:200]!r}")
            return
        if isinstance(a.structured, dict):
            err = a.structured.get("error") if isinstance(a.structured.get("error"), dict) else a.structured
            smsg = str(err.get("message") or "")
            if smsg and not _readable(smsg):
                self.structured_generic.append(label)
        self.r.add("errors", label, "WARN" if slow else "PASS", msg[:140] + slow)

    def _transport(self):
        a = self.m.raw_post(b"{not json")
        self._judge_error("transport: invalid JSON body", a)
        a = self.m.raw_post(json.dumps({"jsonrpc": "2.0", "id": 9, "method": "no/such/method"}).encode())
        self._judge_error("transport: unknown method", a)
        import urllib.request
        import urllib.error
        for label, method, headers, body in (
                ("transport: no bearer", "POST", {"Content-Type": "application/json"},
                 json.dumps({"jsonrpc": "2.0", "id": 1, "method": "tools/list"}).encode()),
                ("transport: GET on the endpoint (SSE probe)", "GET", {"Accept": "text/event-stream"}, None)):
            req = urllib.request.Request(self.m.url, data=body, headers=headers, method=method)
            try:
                with urllib.request.urlopen(req, timeout=30) as r:
                    from mcp_live import Answer
                    ans = Answer(r.status, r.headers.get("Content-Type"), r.read().decode("utf-8", "replace"))
            except urllib.error.HTTPError as e:
                from mcp_live import Answer
                ans = Answer(e.code, e.headers.get("Content-Type"), e.read().decode("utf-8", "replace"))
            if ans.looks_html():
                status = "FAIL" if method == "POST" else "WARN"
                self.r.add("errors", label, status, f"HTML answer (HTTP {ans.status}): {ans.body[:100]!r}")
            elif ans.envelope is None and ans.body.strip():
                self.r.add("errors", label, "WARN", f"HTTP {ans.status}, body not JSON: {ans.body[:100]!r}")
            else:
                self.r.add("errors", label, "PASS", f"HTTP {ans.status} {ans.text[:100] or ans.body[:100]}")

