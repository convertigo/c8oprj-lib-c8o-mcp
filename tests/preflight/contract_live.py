def schema_errors(schema, value, where="$"):
    """The subset of JSON Schema the MCP output schemas use (type, properties, additionalProperties, items, oneOf)."""
    if not isinstance(schema, dict):
        return []
    branches = schema.get("oneOf") or schema.get("anyOf")
    if branches:
        results = [schema_errors(b, value, where) for b in branches]
        return [] if any(not r for r in results) else [f"{where}: matches no branch ({' | '.join(r[0] for r in results)})"]
    kind = ("null" if value is None else "boolean" if isinstance(value, bool) else "number" if isinstance(value, (int, float))
            else "string" if isinstance(value, str) else "array" if isinstance(value, list) else "object")
    types = schema.get("type")
    types = [types] if isinstance(types, str) else (types or [])
    if types and not any(t == kind or (t == "integer" and kind == "number" and float(value).is_integer()) for t in types):
        return [f"{where}: {kind} where the schema takes {'|'.join(types)}"]
    errors = []
    if kind == "object":
        props = schema.get("properties") or {}
        extra = schema.get("additionalProperties")
        for key, item in value.items():
            if key in props:
                errors += schema_errors(props[key], item, f"{where}.{key}")
            elif extra is False:
                errors.append(f"{where}.{key} is not declared and the object is closed")
            elif isinstance(extra, dict):
                errors += schema_errors(extra, item, f"{where}.{key}")
    if kind == "array" and isinstance(schema.get("items"), dict):
        for i, item in enumerate(value):
            errors += schema_errors(schema["items"], item, f"{where}[{i}]")
    return errors


def _message(a):
    d = a.data
    if isinstance(d, dict) and isinstance(d.get("result"), dict) and isinstance(d["result"].get("error"), dict):
        d = d["result"]  # requestable-execute wraps the requestable's answer in result
    if isinstance(d, dict):
        err = d.get("error") if isinstance(d.get("error"), dict) else d
        for k in ("message", "error", "details"):
            if isinstance(err.get(k), str) and err.get(k).strip():
                return err[k]
        errs = d.get("errors")
        if isinstance(errs, list) and errs:
            e = errs[0]
            return e.get("message") if isinstance(e, dict) else str(e)
    return a.text or (json.dumps(a.structured) if a.structured is not None else "")


def _script_cause(err_holder):
    err = err_holder.get("error") if isinstance(err_holder.get("error"), dict) else err_holder
    m = re.search(r"A Javascript error has occured: (?:Error: )?([\s\S]*?)(?: \([^()]*#\d+\))?\s*$", str(err.get("details") or ""))
    return m.group(1).strip() if m else ""


def _readable(msg):
    msg = (msg or "").strip()
    if len(msg) < 12 or any(msg.startswith(g) for g in GENERIC_MESSAGES):
        return False
    if re.match(r"^(Unable to evaluate|java\.|com\.twinsoft|org\.mozilla|EcmaError|TypeError: Cannot)", msg):
        return False
    if re.search(r"\n\s+at [\w.$]+\(", msg):  # a Java stack trace in the message
        return False
    return True


QNAME_LIST_KEYS = ("created", "updated", "deleted", "removed", "touchedQNames", "touchedRoots", "qnames")


def _qname_lists(data):
    """(key, string) for every string inside a list held by a QName list key."""
    out = []

    def walk(n):
        if isinstance(n, dict):
            for k, v in n.items():
                if k in QNAME_LIST_KEYS and isinstance(v, list):
                    out.extend((k, x) for x in v if isinstance(x, str))
                walk(v)
        elif isinstance(n, list):
            for v in n:
                walk(v)
    walk(data)
    return out


def _qnames_in(data):
    out = []

    def walk(n):
        if isinstance(n, dict):
            for k, v in n.items():
                if k in ("qname", "qnames") and isinstance(v, str):
                    out.append(v)
                walk(v)
        elif isinstance(n, list):
            for v in n:
                walk(v)
        elif isinstance(n, str) and n.startswith(P + "."):
            out.append(n)
    walk(data)
    return sorted(set(out))


