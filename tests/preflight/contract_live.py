        self.call("list page", "ngx-page-create", {"project": P, "name": "Items", "kind": "list", "title": "Items", "sequence": "item_list",
                  "list": {"items": "items", "item": "it", "title": "label", "subtitle": "owner"}})
        self.call("form page", "ngx-page-create", {"project": P, "name": "ItemForm", "kind": "form", "title": "New item",
                  "form": {"submit": "item_save", "fields": [{"name": "label", "label": "Label", "required": True}]}})
        self.call("hand sequence", "databaseobject-tree-apply", {"target": P, "at": "inside", "tree": {
            "className": "sequences.GenericSequence", "name": "hand_seq", "properties": {"comment": "Hand-made sequence"},
            "children": [
                {"className": "variables.RequestableVariable", "name": "who"},
                {"className": "steps.SimpleStep", "name": "init", "properties": {"expression": "var ok = true; var n = 0;"}},
                {"className": "steps.IfStep", "name": "ifOk", "properties": {"condition": "ok === true"}, "children": [
                    {"className": "steps.SimpleStep", "name": "inner", "properties": {"expression": "n = 1;"}}]},
                {"className": "steps.JsonToXmlStep", "name": "out", "properties": {"key": "n", "jsonObject": {"mode": "JS", "expression": "n"}}}]}})
        self.call("rename step", "databaseobject-rename", {"qname": P + ".sq:hand_seq.st:init", "name": "start"})
        self.call("move step", "databaseobject-move", {"qname": P + ".sq:hand_seq.st:ifOk.inner", "target": P + ".sq:hand_seq.st:out",
                  "position": "before"})
        self.call("search", "databaseobject-search", {"qname": P, "filter": "item", "limit": 50})
