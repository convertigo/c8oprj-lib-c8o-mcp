  function countTreeNodes(node) {
    if (!node || typeof node !== "object") {
      return 0;
    }
    var total = 1;
    var children = ensureArray(node.children);
    for (var i = 0; i < children.length; i++) {
      total += countTreeNodes(children[i]);
    }
    return total;
  }

